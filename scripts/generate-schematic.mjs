// Generates the demo schematic SVG with tscircuit at build time (Node side,
// where tscircuit runs cleanly) and writes it into the frontend as a module.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Circuit, Board, Resistor, Led, Capacitor, Trace } from "tscircuit";
import { convertCircuitJsonToSchematicSvg } from "circuit-to-svg";

const circuit = new Circuit();
const board = new Board({ width: "14mm", height: "9mm" });
circuit.add(board);

board.add(new Resistor({ name: "R1", resistance: "1k", schX: -4, schY: 0 }));
board.add(new Capacitor({ name: "C1", capacitance: "1uF", schX: 0, schY: 0 }));
board.add(new Led({ name: "L1", schX: 4, schY: 0 }));

board.add(new Trace({ name: "T1", from: "R1.pin1", to: "net.VCC" }));
board.add(new Trace({ name: "T2", from: "R1.pin2", to: "L1.pos" }));
board.add(new Trace({ name: "T3", from: "L1.neg", to: "net.GND" }));

const json = circuit.getCircuitJson();
const svg = convertCircuitJsonToSchematicSvg(json);

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../src/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  resolve(outDir, "schematic.ts"),
  `// Generated by scripts/generate-schematic.mjs (tscircuit). Do not edit.\n` +
    `export const schematicSvg: string = ${JSON.stringify(svg)};\n`,
  "utf8",
);
console.log(`schematic svg generated (${svg.length} chars)`);
